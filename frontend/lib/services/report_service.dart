import 'dart:io';
import 'package:path_provider/path_provider.dart';

class ReportService {
  /// Formats a plant identification report and saves it to
  /// Documents\PlantSage Reports\.  Returns the saved file path.
  static Future<String> exportPlantReport(
      Map<String, dynamic> raw, String? imagePath) async {
    final id   = (raw['identification']    as Map?)?.cast<String, dynamic>() ?? {};
    final suit = (raw['suitability']       as Map?)?.cast<String, dynamic>() ?? {};
    final grow = (raw['growing']           as Map?)?.cast<String, dynamic>() ?? {};
    final sp   = (raw['space']             as Map?)?.cast<String, dynamic>() ?? {};
    final m    = (raw['maintenance']       as Map?)?.cast<String, dynamic>() ?? {};
    final h    = (raw['health']            as Map?)?.cast<String, dynamic>() ?? {};
    final pu   = (raw['purchase_decision'] as Map?)?.cast<String, dynamic>() ?? {};

    final buf = StringBuffer();
    buf.writeln('╔══════════════════════════════════════════╗');
    buf.writeln('║        PlantSage Plant Report            ║');
    buf.writeln('╚══════════════════════════════════════════╝');
    buf.writeln('Generated : ${DateTime.now().toString().substring(0, 16)}');
    buf.writeln();
    buf.writeln('── IDENTIFICATION ──────────────────────────');
    buf.writeln('Common Name  : ${id['plant_name'] ?? '—'}');
    buf.writeln('Scientific   : ${id['scientific_name'] ?? '—'}');
    buf.writeln('Family       : ${id['plant_family'] ?? '—'}');
    buf.writeln('Type         : ${id['plant_type'] ?? '—'}');
    buf.writeln('Confidence   : ${id['confidence_level'] ?? '—'}%');
    buf.writeln();
    buf.writeln('── RECOMMENDATION ──────────────────────────');
    buf.writeln('Overall      : ${pu['recommendation'] ?? '—'}');
    buf.writeln('Score        : ${pu['suitability_score'] ?? raw['suitability_score'] ?? '—'}/100');
    buf.writeln('Decision     : ${pu['buy_or_skip'] ?? '—'}');
    buf.writeln();
    buf.writeln('── GROWING CONDITIONS ──────────────────────');
    buf.writeln('Sunlight     : ${suit['sunlight'] ?? '—'}');
    buf.writeln('Temperature  : ${suit['temperature_range'] ?? '—'}');
    buf.writeln('Humidity     : ${suit['humidity'] ?? '—'}');
    buf.writeln('Climate      : ${suit['climate'] ?? '—'}');
    buf.writeln('Watering     : ${grow['watering'] ?? '—'}');
    buf.writeln('Soil Type    : ${grow['soil_type'] ?? '—'}');
    buf.writeln('Soil pH      : ${grow['soil_ph'] ?? '—'}');
    buf.writeln();
    buf.writeln('── SPACE & GROWTH ──────────────────────────');
    buf.writeln('Height       : ${sp['mature_height'] ?? '—'}');
    buf.writeln('Width        : ${sp['mature_width'] ?? '—'}');
    buf.writeln('Growth Rate  : ${sp['growth_rate'] ?? '—'}');
    buf.writeln('Spacing      : ${sp['spacing'] ?? '—'}');
    buf.writeln();
    buf.writeln('── MAINTENANCE ─────────────────────────────');
    buf.writeln('Difficulty   : ${m['difficulty'] ?? '—'}');
    buf.writeln('Pest Risk    : ${m['pest_susceptibility'] ?? '—'}');
    buf.writeln('Disease Risk : ${m['disease_susceptibility'] ?? '—'}');
    buf.writeln('Pruning      : ${m['pruning'] ?? '—'}');
    buf.writeln();
    buf.writeln('── HEALTH & SAFETY ─────────────────────────');
    buf.writeln('Pet Safe     : ${h['pet_safe'] == true ? 'Yes ✓' : 'No ✗'}');
    buf.writeln('Status       : ${h['health_status'] ?? '—'}');
    buf.writeln();
    if (imagePath != null) buf.writeln('Photo        : $imagePath');
    buf.writeln();
    buf.writeln('Generated by PlantSage — Smart Nursery Advisor');

    final home = await getApplicationDocumentsDirectory();
    final reportsDir = Directory('${home.path}\\PlantSage Reports');
    if (!await reportsDir.exists()) await reportsDir.create(recursive: true);
    final safeName = (id['plant_name'] ?? 'plant')
        .toString()
        .replaceAll(RegExp(r'[<>:"/\\|?*]'), '');
    final date = DateTime.now().toIso8601String().substring(0, 10);
    final file = File('${reportsDir.path}\\${safeName}_$date.txt');
    await file.writeAsString(buf.toString());
    return file.path;
  }

  /// Formats a comparison report and saves it. Returns the file path.
  static Future<String> exportCompareReport(Map<String, dynamic> data) async {
    final p1 = (data['plant1'] as Map).cast<String, dynamic>();
    final p2 = (data['plant2'] as Map).cast<String, dynamic>();

    final buf = StringBuffer();
    buf.writeln('╔══════════════════════════════════════════╗');
    buf.writeln('║      PlantSage Comparison Report         ║');
    buf.writeln('╚══════════════════════════════════════════╝');
    buf.writeln('Generated : ${DateTime.now().toString().substring(0, 16)}');
    buf.writeln();
    _writeCompareSection(buf, p1, p2);

    final home = await getApplicationDocumentsDirectory();
    final reportsDir = Directory('${home.path}\\PlantSage Reports');
    if (!await reportsDir.exists()) await reportsDir.create(recursive: true);
    final n1 = (p1['plant_name'] ?? 'plant1').toString().replaceAll(RegExp(r'[<>:"/\\|?*]'), '');
    final n2 = (p2['plant_name'] ?? 'plant2').toString().replaceAll(RegExp(r'[<>:"/\\|?*]'), '');
    final date = DateTime.now().toIso8601String().substring(0, 10);
    final file = File('${reportsDir.path}\\${n1}_vs_${n2}_$date.txt');
    await file.writeAsString(buf.toString());
    return file.path;
  }

  static void _writeCompareSection(
      StringBuffer buf, Map<String, dynamic> p1, Map<String, dynamic> p2) {
    final d1 = (p1['details'] as Map?)?.cast<String, dynamic>() ?? {};
    final d2 = (p2['details'] as Map?)?.cast<String, dynamic>() ?? {};
    _row(buf, 'Plant', p1['plant_name'], p2['plant_name']);
    _row(buf, 'Scientific', (d1['identification'] as Map?)?['scientific_name'],
        (d2['identification'] as Map?)?['scientific_name']);
    _row(buf, 'Score', '${p1['suitability_score']}/100', '${p2['suitability_score']}/100');
    _row(buf, 'Recommendation', p1['recommendation'], p2['recommendation']);
  }

  static void _row(StringBuffer buf, String label, dynamic v1, dynamic v2) {
    buf.writeln('$label'.padRight(14) + '  ${v1 ?? '—'}'.padRight(28) + '  ${v2 ?? '—'}');
  }
}
